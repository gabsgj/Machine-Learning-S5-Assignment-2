def auc(score, pos):
    score, pos = np.asarray(score, float), np.asarray(pos, bool)
    if pos.all() or (~pos).all():
        return float("nan")
    r = rankdata(score)
    return float((r[pos].sum() - pos.sum() * (pos.sum() + 1) / 2) / (pos.sum() * (~pos).sum()))


def prf(pred, truth):
    pred, truth = np.asarray(pred, bool), np.asarray(truth, bool)
    tp = (pred & truth).sum(); fp = (pred & ~truth).sum(); fn = (~pred & truth).sum()
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    f = 2 * p * r / (p + r) if p + r else 0.0
    return p, r, f


# ---- text baseline (stand-in for a Word2Vec-style *semantic* embedding) -------
def toks(s):
    s = re.sub(r"([a-z])([A-Z])", r"\1 \2", s).replace("_", " ")
    return re.findall(r"[a-z]+", s.lower())


class TfIdf:
    def __init__(self, docs):
        self.vocab = sorted({t for d in docs for t in toks(d)})
        self.ix = {t: i for i, t in enumerate(self.vocab)}
        df = np.zeros(len(self.vocab))
        for d in docs:
            for t in set(toks(d)):
                df[self.ix[t]] += 1
        self.idf = np.log((1 + len(docs)) / (1 + df)) + 1

    def vec(self, d):
        v = np.zeros(len(self.vocab))
        for t in toks(d):
            if t in self.ix:
                v[self.ix[t]] += 1
        return v * self.idf


def text_of(c):
    return f"{c.id} {c.description}"


