def pooled(E, chain_ids, mode):
    es = [E.caps[i] for i in chain_ids]
    comp = E.compose(chain_ids)
    if mode == "mean-pool+sign":
        f = lambda xs: np.sign(np.mean(xs, axis=0))
    else:
        f = lambda xs: np.clip(np.sum(xs, axis=0), -1, 1)
    return dataclasses.replace(comp, pre=f([e.pre for e in es]), grd=f([e.grd for e in es]),
                               eff=f([e.eff for e in es]), valid=True)


