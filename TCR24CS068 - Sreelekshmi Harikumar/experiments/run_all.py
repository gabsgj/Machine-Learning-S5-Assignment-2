rng = np.random.default_rng(5)


def synth(N, d, kp=8, ke=6, p_strict=0.3):
    """Random sparse capabilities; a fraction get a precondition copied from another
    capability's effects so that STRICT / PARTIAL links exist."""
    Pm = np.zeros((N, d)); Em = np.zeros((N, d))
    for i in range(N):
        b = rng.choice(d, ke, replace=False); Em[i, b] = rng.choice([-1, 1], ke)
    for i in range(N):
        if rng.random() < p_strict:
            j = int(rng.integers(N)); nz = np.nonzero(Em[j])[0]
            Pm[i, nz] = Em[j, nz]
        else:
            a = rng.choice(d, kp, replace=False); Pm[i, a] = rng.choice([-1, 1], kp)
    return Pm, Em


def counts(Em, Rm, Pm_base):
    pn = lambda x: ((x > 0).astype(np.float32), (x < 0).astype(np.float32))
    Gm = np.where(Em != 0, Em, Pm_base)
    Gp, Gn = pn(Gm); Rp, Rn = pn(Rm)
    Nv = np.where((Em != 0) & (Em != Pm_base), Em, 0); Vp, Vn = pn(Nv)
    return Gp @ Rp.T + Gn @ Rn.T, Gp @ Rn.T + Gn @ Rp.T, Vp @ Rp.T + Vn @ Rn.T


def labels_from(match, conf, sup, N):
    lab = np.full(match.shape, PARTIAL)
    lab[(match >= N - 0.5) ] = STRICT
    lab[sup < 0.5] = INDEPENDENT
    lab[conf > 0.5] = CONFLICT
    return lab


