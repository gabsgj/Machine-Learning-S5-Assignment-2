"""Generates DELIVERABLE_3_EXPERIMENTAL_DATASET.md tables directly from the JSON files."""
import json, os
H = os.path.dirname(__file__)
ROOT = os.path.dirname(H)
files = ["P0_assignment_minimal", "P1_ecommerce_checkout", "P2_ml_pipeline", "P3_loan_approval"]
res = json.load(open(os.path.join(ROOT, "results", "results.json")))


def lit(l):
    v = l["value"]
    return f"{l['var']} {l['op']} {v}".replace("|", "/")


out = []
out.append("""# Deliverable 3 — Experimental Dataset

Four **formally specified** application problems (JSON, `datasets/`), generated by `datasets/build_datasets.py`.
Every problem provides the full application model $A=(S,C,S_I,G,R,K)$: typed state variables, an initial state, one or more
goal specifications, resources and global constraints, a port-domain hierarchy, environment data, and atomic capabilities with
all eleven capability components. Free-text `description` / `goal_text` fields exist **only** for documentation and for the
text-embedding baseline; the embedding never reads them.

| file | domain | capabilities | state vars | atoms $d_a$ | goals | purpose |
|---|---|---|---|---|---|---|
| `P0_assignment_minimal.json` | e-commerce (minimal) | 3 | 3 | 4 | 1 | the exact CreateOrder / MakePayment / CancelCart pattern of Experiment 1 |
| `P1_ecommerce_checkout.json` | e-commerce | 14 | 17 | 26 | 2 | primary problem: all five experiments |
| `P2_ml_pipeline.json` | data / ML engineering | 15 | 14 | 17 | 2 | FILE / COMPUTATION / GPU resource, integer thresholds |
| `P3_loan_approval.json` | banking / loans | 13 | 13 | 20 | 2 | SERVICE / MESSAGE, human-in-the-loop time window, numeric constraints |

Across the four problems all nine capability types appear (API, DATABASE, GUI, EVENT, FUNCTION, FILE, COMPUTATION, MESSAGE, SERVICE),
all three variable kinds (Boolean, enumerated, integer), required and optional-style inputs, a port-domain hierarchy,
and every operational attribute (time, money, resource cost, risk, energy, reliability, availability window, resource requirements).

## JSON schema (abridged)

```json
{ "problem_id": "...", "domain": "...",
  "state_variables": [ {"name":"Cart.item_count","type":"int","lo":0,"hi":99},
                       {"name":"Payment.status","type":"enum","values":["NOT_STARTED","PENDING","SUCCESS","FAILED"]},
                       {"name":"Order.exists","type":"bool"} ],
  "initial_state": {"Order.exists": false, "Payment.status": "NOT_STARTED", ...},
  "goals": {"main": [{"var":"Payment.status","op":"==","value":"SUCCESS"}], "...": []},
  "resources": [...], "environment": [...],
  "global_constraints": [{"id":"K1","forbid":[ literals that must never hold together ]}],
  "domain_parent": {"positive_decimal": "decimal"},
  "context_ports": [ data available from the start ],
  "capabilities": [ {
      "id":"CreateOrder", "type":"API",
      "inputs":[{"name":"cart_id","type":"UUID","domain":"valid_uuid","required":true}],
      "outputs":[{"name":"order_id","type":"UUID","domain":"valid_uuid"}],
      "preconditions":[{"var":"Cart.item_count","op":">","value":0}],
      "effects":[{"var":"Order.exists","value":true}],
      "constraints":[{"var":"User.role","op":"in","value":["CUSTOMER","ADMIN"]}],
      "resources":["Database","AuthToken"],
      "qos":{"time_ms":60,"money":0.01,"resource_cost":2,"risk":0.01,"energy":0.5},
      "reliability":0.999, "availability":{"available":true,"window":[0,24]},
      "mechanism":{"method":"POST","endpoint":"/orders"},
      "alt_group":"payment"            // ground-truth annotation for Exp. 3 only
  } ] }
```

Operators: `==, !=, >, >=, <, <=, in, not_in`. Effects are assignments `var := value`.

## Ground-truth annotations (used only for evaluation)

* **Pair labels** (CONFLICT / INDEPENDENT / PARTIAL / STRICT) are *not* hand-written. They are produced by an independent
  oracle (`capemb/semantics.py::pair_label`) that enumerates concrete valuations of the variables the two capabilities read
  (all Boolean values, all enum values, integer values at every cut-point ±1 and the domain bounds) and applies the capabilities with concrete semantics.
* **Goal relevance** labels come from brute-force search for *irredundant* goal-reaching sequences (each capability at most once;
  a sequence is irredundant if deleting any step breaks it). A capability is *relevant* iff it occurs in at least one.
* **`alt_group`** marks capabilities that realise the same function through different mechanisms (payment, load, train, verify).

""")
for f in files:
    j = json.load(open(os.path.join(H, f + ".json")))
    out.append(f"## {j['problem_id']}\n")
    out.append(j["description"] + "\n")
    vs = []
    for v in j["state_variables"]:
        d = v["type"] if v["type"] == "bool" else (("{" + ", ".join(v["values"]) + "}") if v["type"] == "enum" else f"int [{v['lo']}, {v['hi']}]")
        vs.append(f"`{v['name']}`: {d}")
    out.append("**State variables:** " + "; ".join(vs) + "\n")
    out.append("**Initial state $S_I$:** " + ", ".join(f"`{k}`={str(v).lower() if isinstance(v,bool) else v}" for k, v in j["initial_state"].items()) + "\n")
    for g, ls in j["goals"].items():
        out.append(f"**Goal `{g}`:** " + " ∧ ".join(f"`{lit(l)}`" for l in ls) + f"  — *{j['goal_text'].get(g,'')}*\n")
    out.append("**Environment resources:** " + ", ".join(j["environment"]) + "\n")
    if j.get("global_constraints"):
        out.append("**Global constraints $K$:** " + "; ".join(f"{k['id']}: never ({' ∧ '.join(lit(l) for l in k['forbid'])}) — {k['description']}" for k in j.get("global_constraints", [])) + "\n")
    out.append("| capability | type | preconditions | constraints | effects | in → out | resources | time ms | money | risk | Rel | window |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for c in j["capabilities"]:
        pre = "; ".join(lit(l) for l in c["preconditions"]) or "—"
        cons = "; ".join(lit(l) for l in c["constraints"]) or "—"
        eff = "; ".join(f"{e['var']} := {e['value']}" for e in c["effects"]) or "—"
        io = ", ".join(p["name"] for p in c["inputs"]) + " → " + (", ".join(p["name"] for p in c["outputs"]) or "∅")
        q = c["qos"]
        w = c["availability"]["window"]
        out.append(f"| {c['id']}{' ⟨'+c['alt_group']+'⟩' if c.get('alt_group') else ''} | {c['type']} | {pre} | {cons} | {eff} | {io} | {', '.join(c['resources']) or '—'} | {q['time_ms']} | {q['money']} | {q['risk']} | {c['reliability']} | {w[0]}–{w[1]} |")
    out.append("")
    # ground-truth summary
    for k, v in res["exp4"].items():
        if k.startswith(j["problem_id"]):
            out.append(f"*Relevant capabilities for goal `{k.split('/')[1]}` (oracle):* {', '.join(v['oracle'])}.\n")
    if f in res["exp1"]:
        d = res["exp1"][f]["dist"]
        out.append(f"*Oracle pair-label distribution over ordered pairs:* " + ", ".join(f"{k} {v}" for k, v in d.items()) + ".\n")
open(os.path.join(ROOT, "DELIVERABLE_3_EXPERIMENTAL_DATASET.md"), "w").write("\n".join(out))
print("ok")
